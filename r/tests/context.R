library(BioDataLedger)
main <- function() {
  root <- tempfile('bdl-context-'); dir.create(root)
  on.exit(unlink(root, recursive = TRUE), add = TRUE)
  writeLines('sample,value\nS1,1', file.path(root, 'data.csv'))
  writeLines('<svg>old</svg>', file.path(root, 'figure.svg'))
  p <- ProjectBundle$create('synthetic context', root)
  error <- function(expr, code) {
    message <- tryCatch({force(expr); NULL}, error = conditionMessage)
    stopifnot(!is.null(message), grepl(code, message, fixed = TRUE))
  }
  d <- p$register_data('data.csv', 'input')
  low <- p$set_design('treatment', c('Vehicle', 'LowDose', 'HighDose'), selected_levels = c('Vehicle', 'LowDose'))
  d <- p$set_data_scope(d, list(condition_values = list('Vehicle', 'LowDose')), 'known', low)
  high <- p$set_design('treatment', c('Vehicle', 'LowDose', 'HighDose'), selected_levels = c('Vehicle', 'HighDose'))
  count <- p$summary()$records
  error(p$register_analysis('wrong', list(d)), 'SCOPE_CONFLICT')
  error(p$register_figure('figure.svg', 'plot', inputs = list(d)), 'SCOPE_CONFLICT')
  stopifnot(p$summary()$records == count)
  a <- p$register_analysis('right', list(d), design_ref = low)
  f <- p$register_figure('figure.svg', 'plot', analysis = a)
  stopifnot(p$check_context(a)$status == 'consistent', identical(p$get_figure(f)$design_ref, low))
  unknown <- p$register_analysis('unknown', list(d), design_ref = NULL)
  stopifnot(p$check_context(unknown)$status == 'unknown')
  all <- p$set_data_scope(d, list(condition_values = list('Vehicle', 'LowDose', 'HighDose')), 'all', low)
  subset <- p$register_analysis('subset', list(all), design_ref = low)
  stopifnot(p$check_context(subset)$status == 'consistent')
  vehicle <- p$set_data_scope(d, list(condition_values = list('Vehicle')), 'vehicle', low)
  treated <- p$set_data_scope(d, list(condition_values = list('LowDose')), 'low', low)
  error(p$register_analysis('separate', list(vehicle, treated), design_ref = low), 'SCOPE_CONFLICT')
  combined <- p$register_analysis('combined', list(vehicle, treated), design_ref = low, input_mode = 'combined')
  combined_figure <- p$register_figure('figure.svg', 'plot', analysis = combined)
  stopifnot(p$check_context(combined)$status == 'consistent', p$get_figure(combined_figure)$input_mode == 'combined')
  missing <- p$register_data('data.csv', 'unknown')
  uncertain <- p$register_analysis('uncertain', list(vehicle, missing), design_ref = low, input_mode = 'combined')
  stopifnot(p$check_context(uncertain)$status == 'unknown')
  other <- p$set_design('cell_type', c('Vehicle', 'LowDose'))
  wrong <- p$set_data_scope(d, list(condition_values = list('Vehicle', 'LowDose')), 'different column', other)
  error(p$register_analysis('different', list(wrong), design_ref = low), 'SCOPE_CONFLICT')
  error(p$update_record(a, list(design_ref = high), 'wrong'), 'SCOPE_CONFLICT')
  error(p$update_record(f, list(inputs = list(d)), 'hidden override'), 'inherits')
  standalone <- p$register_figure('figure.svg', 'plot', inputs = list(d), design_ref = low)
  error(p$update_record(standalone, list(design_ref = high), 'wrong'), 'SCOPE_CONFLICT')
  saved <- p$save_figure('figure.svg', ref = f)
  original_path <- p$resolve_figure(saved, verify = 'sha256')$path
  original_hash <- p$get_figure(f)$sha256
  writeLines('<svg>new</svg>', file.path(root, 'figure.svg'))
  error(p$resolve_figure(f, verify = 'sha256'), 'no preserved copy recorded')
  stopifnot(p$get_figure(f)$sha256 == original_hash)
  second <- p$save_figure('figure.svg', ref = saved)
  stopifnot(second$revision == saved$revision + 1L, p$get_figure(second)$path != original_path,
            readLines(original_path) == '<svg>old</svg>', p$resolve_figure(saved, verify = 'sha256')$verification$file_integrity == 'match')
  error(p$update_record(saved, list(path = 'figure.svg'), 'wrong'), 'save_figure')
  error(p$register_figure('figure.svg', 'plot', artifact_role = 'preserved_copy'), 'Reserved')
  paths <- list.files(file.path(root, '.nb_project_bundle', 'outputs'), full.names = TRUE)
  error(p$save_figure('figure.svg', 'plot', inputs = list(d), design_ref = high), 'SCOPE_CONFLICT')
  stopifnot(identical(paths, list.files(file.path(root, '.nb_project_bundle', 'outputs'), full.names = TRUE)))
  writeLines('# snapshotted original', file.path(root, 'plot.R'))
  standalone_code <- p$register_figure('figure.svg', 'plot', code = 'plot.R', design_ref = NULL)
  unlink(file.path(root, 'plot.R'))
  pending_copy <- p$save_figure('figure.svg', ref = standalone_code)
  p$save()
  persisted_copy <- p$save_figure('figure.svg', ref = pending_copy)
  stopifnot(identical(p$get_figure(persisted_copy)$code, p$get_figure(standalone_code)$code))
  p$set_current(d, 'comparison', 'keep pointer'); p$save()
  one <- ProjectBundle$open(root); two <- ProjectBundle$open(root)
  one_ref <- one$save_figure('figure.svg', 'plot', design_ref = NULL)
  two_ref <- two$save_figure('figure.svg', 'plot', design_ref = NULL)
  stopifnot(one$get_figure(one_ref)$path != two$get_figure(two_ref)$path)
  one$save(); error(two$save(), 'Stale')
  stopifnot(two$status()$unsaved, file.exists(two$get_figure(two_ref)$path))
  # Simulate a 0.4.0 legacy declaration without rewriting it on open.
  path <- file.path(root, '.nb_project_bundle', 'project.json')
  raw <- jsonlite::fromJSON(path, simplifyVector = FALSE)
  raw$schema_version <- '0.3.0'
  raw$records <- lapply(raw$records, function(rec) {
    rec$input_mode <- NULL; rec$preservation <- NULL
    if (identical(rec$id, a$id)) rec$design <- high
    rec
  })
  jsonlite::write_json(raw, path, auto_unbox = TRUE, null = 'null')
  bytes <- readBin(path, 'raw', file.info(path)$size)
  old <- ProjectBundle$open(root)
  stopifnot(old$check_context(a)$status == 'inconsistent', identical(readBin(path, 'raw', file.info(path)$size), bytes))
  named <- old$update_record(a, list(name = 'title'), 'metadata correction')
  stopifnot(old$check_context(named)$status == 'inconsistent')
  fixed <- old$update_record(named, list(design_ref = low), 'correct context'); old$save()
  stopifnot(old$check_context(fixed)$status == 'consistent', old$check_context(a)$status == 'inconsistent', identical(old$get_data(purpose = 'comparison')$ref, d))
}
main()
