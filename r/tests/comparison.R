library(BioDataLedger)
local({
  root <- tempfile("comparison-")
  dir.create(root)
  on.exit(unlink(root, recursive = TRUE), add = TRUE)
  writeLines("synthetic", file.path(root, "input.txt"))
  writeLines("run <- function(...) NULL", file.path(root, "code.R"))
  p <- ProjectBundle$create("synthetic comparison", root)
  data <- p$register_data("input.txt", "input", hash = TRUE)
  original_analysis <- p$register_analysis("original", list(data), code = "code.R", method = "synthetic", params = list(alpha = 1))
  candidate_analysis <- p$register_analysis("candidate", list(data), code = "code.R", method = "synthetic", params = list(alpha = 1))
  original_output <- p$register_data("input.txt", "output", hash = TRUE)
  candidate_output <- p$register_data("input.txt", "candidate output", hash = TRUE)
  original <- list(analysis_ref = original_analysis, outputs = list(list(slot_id = "primary", ref = original_output)))
  candidate <- list(analysis_ref = candidate_analysis, outputs = list(list(slot_id = "primary", ref = candidate_output)))
  criterion <- list(criterion_id = "bytes", required = TRUE, domain = "output", slots = list("primary"), requirement = list(algorithm = "sha256"), comparator_ref = original_analysis, comparison_kind = "bytes")
  intent <- list(input_refs = list(data), retrospective = TRUE)
  fails <- function(expr) inherits(tryCatch(force(expr), error = identity), "error")
  plans <- lapply(c("reproduce", "reapply", "rerender"), function(mode) {
    target <- intent
    if (mode == "reapply") target$input_mapping <- list(list(index = 0L, from = data, to = data))
    if (mode == "rerender") target$visual_changes <- list(theme = "plain")
    p$register_comparison_plan(paste("plan", mode), mode, original, target, list(criterion), "synthetic intent")
  })
  stopifnot(all(vapply(plans, function(ref) identical(p$get_comparison(ref)$record_type, "comparison_plan"), logical(1))))
  stopifnot(all(vapply(plans, function(ref) identical(p$get_decision(ref)$approval, "not_applicable"), logical(1))))
  stopifnot(all(vapply(plans, function(ref) is.null(p$get_decision(ref)$scientific), logical(1))))
  stopifnot(fails(p$record_scientific_decision("bad", "bad", list(list(ref = data)), "approved", ref = plans[[1]])))
  stopifnot(fails(p$register_protocol("bad", list(), "bad", ref = plans[[1]])))
  stopifnot(fails(p$update_record(plans[[1]], list(name = "bad"), "bad")))
  stopifnot(fails(p$register_data("input.txt", "bad", comparison_plan = list())))
  assessment <- p$record_comparison_assessment(plans[[1]], candidate, list(), "no observation")
  report <- p$get_comparison(assessment)
  stopifnot(identical(report$record_type, "comparison_assessment"), identical(report$approval, "not_applicable"),
            identical(report$verdict, "UNKNOWN"), identical(report$criteria[[1]]$effective, "UNKNOWN"),
            "observation_missing" %in% unlist(report$criteria[[1]]$gaps),
            identical(p$get_decision(assessment)$approval, "not_applicable"))
  revised <- p$record_comparison_assessment(plans[[1]], candidate, list(), "revision", assessment)
  stopifnot(revised$revision == 2L,
            fails(p$record_comparison_assessment(plans[[1]], original, list(), "bad binding", assessment)))
  bad <- list(criterion_id = "bytes", verdict = "PASS", observed = list(result = "same"), reason = "declared", evidence = list(data), subjects = list(original_output, candidate_output), comparator_ref = original_analysis)
  bound <- p$record_comparison_assessment(plans[[1]], candidate, list(bad), "unbound evidence")
  bound_report <- p$get_comparison(bound)
  stopifnot(identical(bound_report$criteria[[1]]$effective, "UNKNOWN"), "evidence_binding" %in% unlist(bound_report$criteria[[1]]$gaps))
  evidence <- p$record_decision("evidence", "declared", list(original_output, candidate_output))
  review <- p$record_decision("review", "separate", list(original_output, candidate_output))
  reviewed_criterion <- criterion; reviewed_criterion$comparator_ref <- evidence
  reviewed_plan <- p$register_comparison_plan("reviewed", "reproduce", original, intent, list(reviewed_criterion), "synthetic")
  reviewed_observation <- list(criterion_id = "bytes", verdict = "PASS", observed = "same", reason = "declared", evidence = list(evidence), subjects = list(original_output, candidate_output), comparator_ref = evidence, independent_review_ref = review)
  reviewed <- p$record_comparison_assessment(reviewed_plan, candidate, list(reviewed_observation), "reviewed")
  stopifnot(identical(p$get_comparison(reviewed)$independent_support[[1]]$status, "review_recorded"))
  conflicting <- reviewed_observation; conflicting$contradictory_evidence <- list(review)
  conflict <- p$record_comparison_assessment(reviewed_plan, candidate, list(conflicting), "conflict")
  conflict_view <- p$get_comparison(conflict)
  stopifnot(identical(conflict_view$criteria[[1]]$submitted$verdict, "PASS"), identical(conflict_view$criteria[[1]]$effective, "UNKNOWN"),
            identical(conflict_view$verdict_qualification, "conflicting_evidence"))
  acceptance <- p$record_scientific_decision("accepted", "separate", list(list(ref = reviewed)), "approved")
  stopifnot(identical(p$get_comparison(reviewed, acceptance)$scientific_acceptance$status, "recorded_approved"),
            identical(p$get_comparison(conflict, acceptance)$scientific_acceptance$status, "UNKNOWN"))
  invisible(p$save_and_confirm())
  reopened <- ProjectBundle$open(root)
  stopifnot(identical(reopened$get_comparison(bound)$verdict, "UNKNOWN"))
})
