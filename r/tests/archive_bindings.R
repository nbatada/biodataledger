library(BioDataLedger)
root <- tempfile("archive-bindings-"); stopifnot(dir.create(root, recursive = TRUE))
dir.create(file.path(root, "a")); dir.create(file.path(root, "b"))
writeLines(c("id,label", "001,alpha"), file.path(root, "a", "table.csv"))
writeLines(c("id,label", "002,beta"), file.path(root, "b", "table.csv"))
p <- ProjectBundle$create("archive binding fixture", root)
a <- p$register_metadata(file.path("a", "table.csv"), "sample_preparation", "id", authority = "fixture", reason = "first")
b <- p$register_metadata(file.path("b", "table.csv"), "acquisition", "id", authority = "fixture", reason = "second")
p$save()
archive <- file.path(root, "working.zip")
# Reversed include order makes the old in-place path rewrite swap payload bindings.
p$export_zip(p$preview_export("working", list(b, a)), archive)
q <- ProjectBundle$import_zip(archive, file.path(root, "imported"))
stopifnot(identical(q$get_metadata(a)$bl_rows[[1L]]$label, "alpha"), identical(q$get_metadata(b)$bl_rows[[1L]]$label, "beta"))
cat("PASS: archive payload bindings retain same-basename metadata snapshots\n")
