stopifnot(identical(names(view$bl_categories), c("sample_preparation", "acquisition", "processing_qc", "analysis", "annotation", "result")), length(view$bl_categories$sample_preparation) == 1L)
revised <- p$register_metadata("samples.csv", "sample_preparation", "sample_id", authority = "lab", reason = "correction", ref = samples)
stopifnot(revised$revision == 2L, p$metadata_view(bound)$bl_categories$sample_preparation[[1]]$bl_ref$revision == 1L)
fail(p$bind_metadata(data, list(samples), "historical metadata must not become a new binding"))
