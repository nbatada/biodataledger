fail(p$register_metadata("acquisition.tsv", "acquisition", "sample_id", authority = "instrument", reason = "wrong target", links = list(list(ref = samples, columns = "sample_id", target_columns = "library")), delimiter = "\t"))
writeLines(c("sample_id,note", "001,ok,ragged"), file.path(root, "ragged.csv"))
