stopifnot(identical(table$bl_rows[[1]]$sample_id, "001"), identical(table$bl_rows[[1]]$mouse_id, "M01"), identical(table$bl_rows[[2]]$mouse_id, ""), identical(table$bl_rows[[1]]$note, "NA"), identical(table$bl_rows[[2]]$note, ""), p$check_metadata(bound)$bl_status == "PASS")
