library(BioDataLedger)
root <- tempfile("nb-parity-"); dir.create(root)
writeLines("a", file.path(root, "a.txt")); writeLines("code", file.path(root, "code.R"))
b <- ProjectBundle$create("parity", root, raw_dir = "missing-raw")
d <- b$register_data("a.txt", "qc"); a <- b$register_analysis("analysis", list(d), code = "code.R")
f <- b$register_figure("a.txt", "qc", analysis = a)
writeLines("changed code", file.path(root, "code.R"))
b$save()
stopifnot(b$get_figure(f)$source_code_availability[[1]])
old <- b$update_record(d, list(name = "old"), "correction")
stopifnot(b$get_data(role = "qc")$ref$revision == 2)
b$save()
file.remove(file.path(root, "a.txt"))
stopifnot(inherits(try(b$preview_export("working", list(d)), silent = TRUE), "try-error"))
